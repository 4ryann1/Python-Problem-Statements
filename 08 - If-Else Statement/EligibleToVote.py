# Take the user's age as input. Print whether the person is eligible to vote or not.
# Assume the minimum voting age is 18.

age = int(input("Enter your age: "))

if age >= 18:
    print(f"You are old enough to vote")
elif age < 18:
    print(f"You are old enough to vote")
else:
    print(f"Invalid input: {age}")