"""Problem 12: Tuple Unpacking

Create a Python program containing a tuple with a person's name, age, and city.
Use tuple unpacking to store each value in a separate variable and display them.

Example:
Tuple: ("Aryan", 21, "Pune")
Output:
Name: Aryan
Age: 21
City: Pune
"""

# Write your solution below.

Tuple = ("Aryan", 21, "Pune")
print("Name: ", Tuple[0])
print("Age: ", Tuple[1])
print("City: ", Tuple[2])