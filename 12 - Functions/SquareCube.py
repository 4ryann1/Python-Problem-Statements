# 4. Calculate Square and Cube
# Create two functions:
#
# square(n)
# cube(n)
#
# Return the square and cube of the given number.
#
# Example:
#
# Input: 5
# Square: 25
# Cube: 125

def square(n):
    square = n**2
    return square

def cube(n):
    cube = n**3
    return cube

print(square(5))
print(cube(5))